export function narrationPlan(events) {
  let start=0;
  return events.map(event=>{
    const lines=NARRATION_SCRIPTS[event.id];
    if(!lines?.length)throw Error(`缺少配音讲解：${event.id}`);
    const item={eventId:event.id,start:Number(start.toFixed(6)),duration:event.duration,lines};
    start+=event.duration;return item;
  });
}

export function captionAt(cues,time) {
  let lo=0,hi=cues.length;
  while(lo<hi){const mid=(lo+hi)>>>1;if(cues[mid].start<=time+1e-7)lo=mid+1;else hi=mid;}
  const index=lo-1;
  return index>=0&&time<cues[index].end?index:-1;
}

// Text-only fallback still covers the complete timeline when an audio asset cannot load.
export function fallbackCaptions(events) {
  return narrationPlan(events).flatMap(event=>{
    const weights=event.lines.map(line=>line.length),sum=weights.reduce((a,b)=>a+b,0);let elapsed=0;
    return event.lines.map((text,i)=>{
      const start=event.start+elapsed;elapsed+=event.duration*weights[i]/sum;
      return {eventId:event.eventId,start,end:i===event.lines.length-1?event.start+event.duration:event.start+elapsed,text};
    });
  });
}

