export const PRC_PLAYBACK_SECONDS = 8 * 60; // 480 seconds (8 minutes)

const PRC_BRIEF_EVENTS = new Set(['prc-m-5', 'prc-m-9', 'prc-e-10', 'prc-m-13', 'prc-m-14']);
const PRC_RICH_EVENTS = new Set(['prc-w-2', 'prc-m-16', 'prc-l-3', 'prc-e-7', 'prc-w-1', 'prc-m-18', 'prc-m-17', 'prc-l-4']);

/** Allocate teaching time across the 36 PRC nodes by complexity & spoken density, totaling exact targetSeconds. */
export function storyboardPrcEvents(events, targetSeconds = PRC_PLAYBACK_SECONDS) {
  const weights = events.map((e) =>
    PRC_HERO_IDS.has(e.id)
      ? 16.5
      : PRC_BRIEF_EVENTS.has(e.id)
        ? 9.2
        : PRC_RICH_EVENTS.has(e.id)
          ? 14.5
          : PRC_KEY_EVENTS.has(e.id)
            ? 13.5
            : 12.2,
  );
  const sum = weights.reduce((a, b) => a + b, 0);
  const exact = weights.map((w) => (w / sum) * Math.round(targetSeconds * 10));
  const ticks = exact.map(Math.floor);
  const order = exact
    .map((value, i) => ({ i, remainder: value - ticks[i] }))
    .sort((a, b) => b.remainder - a.remainder);
  const remaining = Math.round(targetSeconds * 10) - ticks.reduce((a, b) => a + b, 0);
  for (let i = 0; i < remaining; i += 1) ticks[order[i].i] += 1;
  return events.map((event, i) => ({ ...event, duration: ticks[i] / 10 }));
}
