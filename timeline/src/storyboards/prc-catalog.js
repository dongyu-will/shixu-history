const S = (short, title, text) => ({ short, title, text });
const make = (mode, steps, visual, evidence = []) => ({
  kind: 'process',
  mode,
  duration: steps.length * 7,
  center: [104, 32],
  scale: 730,
  sources: [],
  evidence,
  beats: steps.map((beat, i) => ({ ...beat, at: i * 7 })),
  ...visual,
});

const chain = (steps, labels, extra = {}) => make('chain', steps, { labels, ...extra });
const fork = (steps, root, branches, result, extra = {}) => make('fork', steps, { root, branches, result, ...extra });
const union = (steps, groups, result, extra = {}) => make('union', steps, { groups, result, ...extra });
const debate = (steps, sides, result, extra = {}) => make('debate', steps, { sides, result, ...extra });
const cycle = (steps, labels, extra = {}) => make('cycle', steps, { labels, ...extra });
const map = (steps, locations, edges = [], extra = {}) => make('geography', steps, { locations, edges, ...extra });
const land = (steps, allocation, donor, recipient, note, extra = {}) =>
  make('land', steps, { allocation, donor, recipient, note, ...extra });
const seats = (steps, groups, result, extra = {}) => make('seats', steps, { groups, result, ...extra });

