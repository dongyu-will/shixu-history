export function prcNarrationPlan(timeline) {
  let start = 0;
  return timeline.map((event) => {
    const lines = PRC_NARRATION_SCRIPTS[event.id];
    if (!lines?.length) throw new Error(`Missing PRC narration script for ${event.id}`);
    const item = {
      eventId: event.id,
      title: event.title,
      start: Number(start.toFixed(6)),
      end: Number((start + event.duration).toFixed(6)),
      duration: event.duration,
      lines,
    };
    start += event.duration;
    return item;
  });
}

export function prcFallbackCaptions(timeline) {
  return prcNarrationPlan(timeline).flatMap((item) => {
    const totalChars = item.lines.reduce((sum, line) => sum + line.length, 0);
    let cursor = item.start;
    return item.lines.map((text, index) => {
      const end =
        index === item.lines.length - 1
          ? item.end
          : cursor + (item.duration * text.length) / totalChars;
      const cue = { eventId: item.eventId, start: cursor, end, text };
      cursor = end;
      return cue;
    });
  });
}
